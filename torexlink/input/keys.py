MODIFIER_NAMES = frozenset({"ctrl", "alt", "shift", "meta", "caps"})
MODIFIER_KEYS = frozenset(
    {"ctrl", "right_ctrl", "alt", "right_alt", "shift", "right_shift", "meta", "right_meta"}
)

# Quartz event flag masks
MAC_MOD_MASKS = {
    "shift": 0x00020000,
    "ctrl": 0x00040000,
    "alt": 0x00080000,
    "meta": 0x00100000,
    "caps": 0x00010000,
}


def is_modifier_key(key: str) -> bool:
    return key in MODIFIER_KEYS


def modifier_aliases(key: str) -> tuple[str, ...]:
    if key in {"ctrl", "right_ctrl"}:
        return ("ctrl",)
    if key in {"alt", "right_alt"}:
        return ("alt",)
    if key in {"shift", "right_shift"}:
        return ("shift",)
    if key in {"meta", "right_meta"}:
        return ("meta",)
    if key == "caps_lock":
        return ("caps",)
    return ()


