_CATALOGUES: dict[str, dict[str, str]] = {"uz": UZ, "ru": RU, "en": EN}


class Translator:
    def __init__(self, locale: str = DEFAULT_LOCALE) -> None:
        self._locale = locale if locale in SUPPORTED_LOCALES else DEFAULT_LOCALE

    @property
    def locale(self) -> str:
        return self._locale

    @property
    def locale_name(self) -> str:
        return LOCALE_NAMES[self._locale]

    def set_locale(self, locale: str) -> None:
        if locale in SUPPORTED_LOCALES:
            self._locale = locale

    def t(self, key: str, **params: object) -> str:
        catalogue = _CATALOGUES.get(self._locale, UZ)
        text = catalogue.get(key)
        if text is None:
            fallback = UZ.get(key)
            if fallback is None:
                log.warning("Missing translation key: %s", key)
                return key
            text = fallback
        if params:
            try:
                return text.format(**params)
            except (KeyError, IndexError, ValueError):
                log.warning("Translation formatting failed for %s", key)
                return text
        return text

    def available_locales(self) -> list[tuple[str, str]]:
        return [(locale, LOCALE_NAMES[locale]) for locale in SUPPORTED_LOCALES]


def catalogues() -> dict[str, dict[str, str]]:
    return _CATALOGUES


